/* ==========================================================================
   LiHui International Logistics — site behaviour
   Vanilla JS, no dependencies. Language bundle and config come from
   assets/js/i18n.js (generated by tools/build.mjs).
   ========================================================================== */
(function () {
  'use strict';

  var I18N = window.LH_I18N || { ru: {} };
  var CONFIG = window.LH_CONFIG || {};
  var LANG_KEY = 'lh-lang';
  var FAV_KEY = 'lh-fav';
  var COOKIE_KEY = 'lh-notice';
  var HTML_KEYS = { 'home.title': 1 };
  var langs = ['ru', 'en', 'zh'];

  var site = CONFIG.site || {};
  var modes = CONFIG.modes || { air: { divisor: 6000 }, ground: { divisor: 6000 } };
  var pricing = CONFIG.pricing || { enabled: false, currency: 'RUB', rates: {} };
  var lastCalc = null;

  /* --------------------------------------------------------------- helpers */

  function $(selector, scope) {
    return (scope || document).querySelector(selector);
  }

  function $$(selector, scope) {
    return Array.prototype.slice.call((scope || document).querySelectorAll(selector));
  }

  function store(key, value) {
    try {
      if (value === undefined) return window.localStorage.getItem(key);
      if (value === null) window.localStorage.removeItem(key);
      else window.localStorage.setItem(key, value);
    } catch (error) {
      /* storage can be blocked (private mode) — the site keeps working */
    }
    return null;
  }

  function dict(lang) {
    return I18N[lang] || I18N.ru || {};
  }

  function t(key, lang) {
    var active = lang || document.documentElement.getAttribute('data-lang') || 'ru';
    var value = dict(active)[key];
    if (value === undefined) value = dict('ru')[key];
    return value === undefined ? '' : value;
  }

  function setText(node, key, lang) {
    var value = t(key, lang);
    if (!value) return;
    if (HTML_KEYS[key]) node.innerHTML = value;
    else node.textContent = value;
  }

  var toastTimer = null;
  function toast(message) {
    var node = $('#toast');
    if (!node || !message) return;
    node.textContent = message;
    node.classList.add('is-visible');
    window.clearTimeout(toastTimer);
    toastTimer = window.setTimeout(function () {
      node.classList.remove('is-visible');
    }, 3200);
  }

  function copy(text) {
    if (navigator.clipboard && navigator.clipboard.writeText) {
      return navigator.clipboard.writeText(text);
    }
    return new Promise(function (resolve, reject) {
      try {
        var area = document.createElement('textarea');
        area.value = text;
        area.setAttribute('readonly', '');
        area.style.position = 'fixed';
        area.style.opacity = '0';
        document.body.appendChild(area);
        area.select();
        var ok = document.execCommand('copy');
        document.body.removeChild(area);
        ok ? resolve() : reject();
      } catch (error) {
        reject(error);
      }
    });
  }

  /* ---------------------------------------------------------- localisation */

  function applyLang(lang, options) {
    var settings = options || {};
    var next = langs.indexOf(lang) === -1 ? 'ru' : lang;
    document.documentElement.setAttribute('data-lang', next);
    document.documentElement.setAttribute('lang', next === 'zh' ? 'zh-Hans' : next);

    $$('[data-i18n]').forEach(function (node) {
      setText(node, node.getAttribute('data-i18n'), next);
    });
    $$('[data-i18n-ph]').forEach(function (node) {
      var value = t(node.getAttribute('data-i18n-ph'), next);
      if (value) node.setAttribute('placeholder', value);
    });
    $$('[data-i18n-title]').forEach(function (node) {
      var value = t(node.getAttribute('data-i18n-title'), next);
      if (value) node.setAttribute('title', value);
    });
    $$('[data-i18n-aria]').forEach(function (node) {
      var value = t(node.getAttribute('data-i18n-aria'), next);
      if (value) node.setAttribute('aria-label', value);
    });
    [['data-i18n-desc', 'name', 'description'], ['data-i18n-ogtitle', 'property', 'og:title'], ['data-i18n-ogdesc', 'property', 'og:description']].forEach(function (rule) {
      var node = document.querySelector('meta[' + rule[1] + '="' + rule[2] + '"]');
      if (node && node.hasAttribute(rule[0])) {
        var value = t(node.getAttribute(rule[0]), next);
        if (value) node.setAttribute('content', value);
      }
    });
    [['data-i18n-twtitle', 'twitter:title'], ['data-i18n-twdesc', 'twitter:description']].forEach(function (rule) {
      var node = document.querySelector('meta[name="' + rule[1] + '"]');
      if (node && node.hasAttribute(rule[0])) {
        var value = t(node.getAttribute(rule[0]), next);
        if (value) node.setAttribute('content', value);
      }
    });

    $$('.lang button').forEach(function (button) {
      button.setAttribute('aria-pressed', button.getAttribute('data-lang') === next ? 'true' : 'false');
    });

    var titleNode = document.querySelector('title[data-i18n-doctitle]');
    if (titleNode) {
      var titleValue = t(titleNode.getAttribute('data-i18n-doctitle'), next);
      if (titleValue) titleNode.textContent = titleValue;
    }

    if (lastCalc) renderResult(lastCalc, next);
    if (settings.persist !== false) store(LANG_KEY, next);
    document.dispatchEvent(new CustomEvent('lh:lang', { detail: { lang: next } }));
  }

  function initialLang() {
    var fromUrl = new URLSearchParams(window.location.search).get('lang');
    if (fromUrl && langs.indexOf(fromUrl) !== -1) return fromUrl;
    var saved = store(LANG_KEY);
    if (saved && langs.indexOf(saved) !== -1) return saved;
    var browser = (navigator.language || '').toLowerCase();
    if (browser.indexOf('zh') === 0) return 'zh';
    if (browser.indexOf('en') === 0) return 'en';
    return 'ru';
  }

  /* ------------------------------------------------------------- messaging */

  function chatUrl(channel, text) {
    var base = channel === 'whatsapp' ? site.whatsapp : site.telegram;
    if (!base) return '#';
    return base + '?text=' + encodeURIComponent(text);
  }

  function openChat(channel, text, meta) {
    var url = chatUrl(channel, text);
    var opened = window.open(url, '_blank', 'noopener');
    track('contact_click', Object.assign({ channel: channel }, meta || {}));
    if (!opened) {
      copy(text).then(
        function () {
          toast(t('ui.copied'));
        },
        function () {
          toast(t('ui.copyFail'));
        },
      );
    }
  }

  function line(labelKey, value) {
    return value ? t(labelKey) + ': ' + value : '';
  }

  function buildPageFooter() {
    return t('msg.page') + ': ' + window.location.href;
  }

  function buildRequestMessage(data) {
    var lines = [
      t('msg.title'),
      '',
      line('msg.name', data.name),
      line('msg.topic', data.topic),
      line('msg.destination', data.destination),
      line('msg.cargo', data.cargo),
      '',
      buildPageFooter(),
    ];
    return lines.filter(function (value) {
      return value !== '';
    }).join('\n');
  }

  function buildCalcMessage(data) {
    return [
      t('msg.calcTitle'),
      '',
      line('msg.destination', data.destination),
      line('msg.mode', data.modeLabel),
      t('msg.volume') + ': ' + data.volume + ' ' + t('ui.m3'),
      t('msg.volWeight') + ': ' + data.volWeight + ' ' + t('ui.kg'),
      t('msg.actual') + ': ' + data.actual + ' ' + t('ui.kg'),
      t('msg.chargeable') + ': ' + data.chargeable + ' ' + t('ui.kg'),
      '',
      buildPageFooter(),
    ].join('\n');
  }

  /* ------------------------------------------------------------- analytics */

  function track(event, payload) {
    window.dataLayer = window.dataLayer || [];
    window.dataLayer.push(Object.assign({ event: 'lh_' + event }, payload || {}));
  }

  /* ------------------------------------------------------------ calculator */

  function num(id) {
    var node = document.getElementById(id);
    if (!node) return 0;
    var value = parseFloat(String(node.value).replace(',', '.'));
    return isNaN(value) ? 0 : value;
  }

  function fmt(value, digits) {
    var factor = Math.pow(10, digits === undefined ? 1 : digits);
    var rounded = Math.round(value * factor) / factor;
    return String(rounded);
  }

  function compute(input) {
    var divisor = (modes[input.mode] || modes.air || { divisor: 6000 }).divisor;
    var volume = (input.l * input.w * input.h * input.pieces) / 1000000;
    var volWeight = (input.l * input.w * input.h * input.pieces) / divisor;
    var chargeable = Math.max(volWeight, input.actual);
    return {
      volume: volume,
      volWeight: volWeight,
      actual: input.actual,
      chargeable: chargeable,
      byVolume: volWeight >= input.actual,
    };
  }

  function priceFor(cityKey, modeKey) {
    if (!pricing.enabled || !pricing.rates) return null;
    return pricing.rates[cityKey + ':' + modeKey] || null;
  }

  function renderResult(input, lang) {
    var output = compute(input);
    var result = $('#calcResult');
    if (!result) return;

    var cityNode = $('#calcDestination');
    var cityKey = cityNode ? cityNode.value : '';
    var cityName = cityNode ? (cityNode.options[cityNode.selectedIndex] || {}).textContent : '';
    var modeLabel = input.mode === 'ground' ? t('calc.modeGround', lang) : t('calc.modeAir', lang);
    var set = function (id, value) {
      var node = document.getElementById(id);
      if (node) node.textContent = value;
    };

    set('calcVolume', fmt(output.volume, 3) + ' ' + t('ui.m3', lang));
    set('calcVolWeight', fmt(output.volWeight, 1) + ' ' + t('ui.kg', lang));
    set('calcActualOut', fmt(output.actual, 1) + ' ' + t('ui.kg', lang));
    set('calcChargeable', fmt(output.chargeable, 1) + ' ' + t('ui.kg', lang));
    set('calcBadge', output.byVolume ? t('calc.byVol', lang) : t('calc.byActual', lang));

    var priceNode = $('#calcPrice');
    var price = priceFor(cityKey, input.mode);
    if (priceNode) {
      if (price && price.min) {
        priceNode.hidden = false;
        priceNode.textContent = t('calc.priceRange', lang) + ': ' + price.min + '–' + price.max + ' ' + (pricing.currency || '') + ' / ' + t('ui.kg', lang);
      } else {
        priceNode.hidden = true;
        priceNode.textContent = '';
      }
    }

    result.hidden = false;
    lastCalc = input;
    lastCalc.destination = cityName;
    lastCalc.modeLabel = modeLabel;
    lastCalc.volume = fmt(output.volume, 3);
    lastCalc.volWeight = fmt(output.volWeight, 1);
    lastCalc.actual = fmt(output.actual, 1);
    lastCalc.chargeable = fmt(output.chargeable, 1);

    var quote = $('#calcQuote');
    if (quote) quote.href = chatUrl('telegram', buildCalcMessage(lastCalc));
    return output;
  }

  function initCalculator() {
    var form = $('#calcForm');
    if (!form) return;

    form.addEventListener('submit', function (event) {
      event.preventDefault();
      var fields = ['calcLength', 'calcWidth', 'calcHeight', 'calcActual'];
      var input = {
        l: num('calcLength'),
        w: num('calcWidth'),
        h: num('calcHeight'),
        pieces: Math.max(1, Math.round(num('calcPieces')) || 1),
        actual: num('calcActual'),
        mode: ($('#calcMode') || {}).value || 'air',
      };
      var valid = input.l > 0 && input.w > 0 && input.h > 0 && input.actual > 0;
      fields.forEach(function (id) {
        var field = document.getElementById(id);
        if (field && field.parentNode) field.parentNode.classList.toggle('is-invalid', !valid && !num(id));
      });
      if (!valid) {
        toast(t('calc.error'));
        return;
      }
      renderResult(input);
      track('calc_submit', { destination: ($('#calcDestination') || {}).value, mode: input.mode });
      var result = $('#calcResult');
      if (result && result.scrollIntoView) result.scrollIntoView({ behavior: 'smooth', block: 'center' });
    });

    form.addEventListener('reset', function () {
      window.setTimeout(function () {
        var result = $('#calcResult');
        if (result) result.hidden = true;
        lastCalc = null;
        $$('.field.is-invalid').forEach(function (field) {
          field.classList.remove('is-invalid');
        });
        toast(t('calc.resetDone'));
      }, 0);
    });

    var print = $('#calcPrint');
    if (print) print.addEventListener('click', function () {
      window.print();
    });
  }

  /* ----------------------------------------------------------------- forms */

  function selectedText(select) {
    if (!select) return '';
    var option = select.options[select.selectedIndex];
    return option ? option.textContent : '';
  }

  function markInvalid(node, invalid) {
    if (!node || !node.parentNode) return;
    node.parentNode.classList.toggle('is-invalid', !!invalid);
  }

  function initQuoteForm() {
    var form = $('#quoteForm');
    if (!form) return;
    var cargo = $('#quoteCargo');
    var city = $('#quoteCity');

    function send(channel) {
      var text = (cargo && cargo.value ? cargo.value : '').trim();
      if (!text) {
        markInvalid(cargo, true);
        toast(t('ui.errorForm'));
        if (cargo) cargo.focus();
        return;
      }
      markInvalid(cargo, false);
      openChat(
        channel,
        buildRequestMessage({ cargo: text, destination: selectedText(city), topic: t('contact.topicDelivery') }),
        { source: 'hero_quote', channel: channel },
      );
    }

    form.addEventListener('submit', function (event) {
      event.preventDefault();
      send('telegram');
    });
    var wa = $('#quoteWa');
    if (wa) wa.addEventListener('click', function () {
      send('whatsapp');
    });
    if (cargo) cargo.addEventListener('input', function () {
      markInvalid(cargo, false);
    });
  }

  function initRequestForm() {
    var form = $('#requestForm');
    if (!form) return;

    function send(channel) {
      var name = $('#reqName');
      var topic = $('#reqTopic');
      var city = $('#reqCity');
      var message = $('#reqMsg');
      var text = (message && message.value ? message.value : '').trim();
      if (!text) {
        markInvalid(message, true);
        toast(t('ui.errorForm'));
        if (message) message.focus();
        return;
      }
      markInvalid(message, false);
      openChat(
        channel,
        buildRequestMessage({
          name: name && name.value ? name.value.trim() : '',
          topic: selectedText(topic),
          destination: selectedText(city),
          cargo: text,
        }),
        { source: 'request_form', channel: channel, topic: topic ? topic.value : '' },
      );
    }

    form.addEventListener('submit', function (event) {
      event.preventDefault();
      send('telegram');
    });
    var wa = $('#reqWa');
    if (wa) wa.addEventListener('click', function () {
      send('whatsapp');
    });
    var message = $('#reqMsg');
    if (message) message.addEventListener('input', function () {
      markInvalid(message, false);
    });
  }

  function initTrackForm() {
    var form = $('#trackForm');
    if (!form) return;
    form.addEventListener('submit', function (event) {
      event.preventDefault();
      var input = $('#trackInput');
      var value = input && input.value ? input.value.trim() : '';
      if (!value) {
        markInvalid(input, true);
        if (input) input.focus();
        return;
      }
      markInvalid(input, false);
      openChat('telegram', t('msg.track') + '\n' + t('msg.trackNumber') + ': ' + value + '\n\n' + buildPageFooter(), {
        source: 'track_form',
      });
    });
  }

  /* ------------------------------------------------------------ navigation */

  function initNav() {
    var burger = $('#burger');
    var drawer = $('#drawer');
    if (!burger || !drawer) return;

    function setOpen(open) {
      burger.setAttribute('aria-expanded', open ? 'true' : 'false');
      drawer.hidden = !open;
      document.body.classList.toggle('is-locked', open);
    }

    burger.addEventListener('click', function () {
      setOpen(burger.getAttribute('aria-expanded') !== 'true');
      track('menu_toggle', { open: burger.getAttribute('aria-expanded') === 'true' });
    });
    drawer.addEventListener('click', function (event) {
      if (event.target.tagName === 'A') setOpen(false);
    });
    document.addEventListener('keydown', function (event) {
      if (event.key === 'Escape') {
        setOpen(false);
        closeShare();
      }
    });
    window.addEventListener('resize', function () {
      if (window.innerWidth > 1100) setOpen(false);
    });
  }

  function initScroll() {
    var header = $('#header');
    var bar = $('#progress span');
    var top = $('#toTop');

    function update() {
      var doc = document.documentElement;
      var max = doc.scrollHeight - doc.clientHeight;
      var y = window.pageYOffset || doc.scrollTop || 0;
      if (bar) bar.style.width = (max > 0 ? Math.min(100, (y / max) * 100) : 0) + '%';
      if (header) header.classList.toggle('is-stuck', y > 8);
      if (top) top.classList.toggle('is-visible', y > 700);
    }

    var ticking = false;
    window.addEventListener(
      'scroll',
      function () {
        if (ticking) return;
        ticking = true;
        window.requestAnimationFrame(function () {
          update();
          parallax();
          ticking = false;
        });
      },
      { passive: true },
    );
    update();

    if (top) top.addEventListener('click', function () {
      window.scrollTo({ top: 0, behavior: 'smooth' });
    });
    var progress = $('#progress');
    if (progress) progress.addEventListener('click', function () {
      window.scrollTo({ top: 0, behavior: 'smooth' });
    });
  }

  function parallax() {
    if (window.matchMedia && window.matchMedia('(prefers-reduced-motion: reduce)').matches) return;
    var media = $('.hero__media');
    if (!media) return;
    var offset = Math.min(90, (window.pageYOffset || 0) * 0.08);
    media.style.transform = 'translate3d(0,' + offset + 'px,0)';
  }

  function initReveal() {
    var nodes = $$('.reveal');
    if (!nodes.length) return;
    if (!('IntersectionObserver' in window)) {
      nodes.forEach(function (node) {
        node.classList.add('is-visible');
      });
      return;
    }
    var observer = new IntersectionObserver(
      function (entries) {
        entries.forEach(function (entry) {
          if (entry.isIntersecting) {
            entry.target.classList.add('is-visible');
            observer.unobserve(entry.target);
          }
        });
      },
      { rootMargin: '0px 0px -80px 0px', threshold: 0.08 },
    );
    nodes.forEach(function (node) {
      observer.observe(node);
    });
  }

  /* ---------------------------------------------------------- share / save */

  function shareUrl() {
    return window.location.href.split('#')[0];
  }

  function closeShare() {
    var panel = $('#sharePanel');
    var toggle = $('#shareToggle');
    if (panel) panel.hidden = true;
    if (toggle) toggle.setAttribute('aria-expanded', 'false');
  }

  function initShare() {
    var panel = $('#sharePanel');
    var toggle = $('#shareToggle');
    var copyButton = $('#copyShareBtn');
    if (!panel || !toggle) return;

    var url = shareUrl();
    var targets = {
      telegram: 'https://t.me/share/url?url=' + encodeURIComponent(url) + '&text=' + encodeURIComponent(document.title),
      whatsapp: 'https://api.whatsapp.com/send?text=' + encodeURIComponent(document.title + ' ' + url),
      vk: 'https://vk.com/share.php?url=' + encodeURIComponent(url),
    };
    $$('[data-share]', panel).forEach(function (link) {
      var key = link.getAttribute('data-share');
      if (targets[key]) link.href = targets[key];
    });

    toggle.addEventListener('click', function () {
      if (navigator.share) {
        navigator.share({ title: document.title, url: url }).catch(function () {});
        track('share', { via: 'native' });
        return;
      }
      var open = panel.hidden;
      panel.hidden = !open;
      toggle.setAttribute('aria-expanded', open ? 'true' : 'false');
      if (open) track('share', { via: 'panel' });
    });

    if (copyButton) copyButton.addEventListener('click', function () {
      copy(url).then(
        function () {
          toast(t('ui.copied'));
        },
        function () {
          toast(t('ui.copyFail'));
        },
      );
    });

    document.addEventListener('click', function (event) {
      if (panel.hidden) return;
      if (panel.contains(event.target) || toggle.contains(event.target)) return;
      closeShare();
    });
  }

  function initFavorite() {
    var button = $('#favoriteToggle');
    if (!button) return;
    var star = '<svg class="icon" viewBox="0 0 24 24" aria-hidden="true"><path fill="none" stroke="currentColor" stroke-width="1.8" stroke-linejoin="round" d="m12 4 2.5 5.2 5.5.8-4 4 1 5.5-5-2.8-5 2.8 1-5.5-4-4 5.5-.8Z"/></svg>';
    var starOn = '<svg class="icon" viewBox="0 0 24 24" aria-hidden="true"><path fill="currentColor" d="m12 4 2.5 5.2 5.5.8-4 4 1 5.5-5-2.8-5 2.8 1-5.5-4-4 5.5-.8Z"/></svg>';

    function set(on, notify) {
      button.innerHTML = on ? starOn : star;
      button.setAttribute('aria-pressed', on ? 'true' : 'false');
      store(FAV_KEY, on ? '1' : null);
      if (notify) toast(on ? t('ui.favoriteOn') : t('ui.favoriteOff'));
    }

    set(store(FAV_KEY) === '1', false);
    button.addEventListener('click', function () {
      var next = button.getAttribute('aria-pressed') !== 'true';
      set(next, true);
      track('favorite', { on: next });
    });
  }

  function initNotice() {
    var notice = $('#cookie');
    var ok = $('#cookieOk');
    if (!notice || !ok) return;
    if (store(COOKIE_KEY) === '1') {
      notice.hidden = true;
      return;
    }
    notice.hidden = false;
    ok.addEventListener('click', function () {
      store(COOKIE_KEY, '1');
      notice.hidden = true;
    });
  }

  function initLangButtons() {
    $$('.lang button').forEach(function (button) {
      button.addEventListener('click', function () {
        var lang = button.getAttribute('data-lang');
        applyLang(lang);
        track('lang_change', { lang: lang });
      });
    });
  }

  function initHashFocus() {
    if (window.location.hash !== '#request') return;
    var message = $('#reqMsg');
    if (message) {
      window.setTimeout(function () {
        message.focus({ preventScroll: true });
      }, 300);
    }
  }

  /* ------------------------------------------------------------------ boot */

  function boot() {
    applyLang(initialLang(), { persist: false });
    initLangButtons();
    initNav();
    initScroll();
    initReveal();
    initCalculator();
    initQuoteForm();
    initRequestForm();
    initTrackForm();
    initShare();
    initFavorite();
    initNotice();
    initHashFocus();

    var lang = document.documentElement.getAttribute('data-lang') || 'ru';
    track('page_view', { page: document.body.getAttribute('data-page') || 'unknown', lang: lang });
  }

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', boot);
  } else {
    boot();
  }

  window.LH = { applyLang: applyLang, toast: toast, t: t, compute: compute };
})();
